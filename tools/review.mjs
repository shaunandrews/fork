#!/usr/bin/env node
// Fork review: browse screenshots (from tools/shoot.mjs) across flows and
// viewports, and pin comments on elements or areas.
//
//   node tools/review.mjs                     # open the review app on http://127.0.0.1:4300
//   node tools/review.mjs list                # print open feedback
//   node tools/review.mjs reply <id> "text"   # answer a comment
//   node tools/review.mjs resolve <id> "text" # answer and mark it resolved
//   node tools/review.mjs reopen <id>
//
// Comments live in review/comments.json, with a crop of each spot in
// review/crops/ and a readable summary in review/FEEDBACK.md. See DEV.md.
import { createServer } from "node:http";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, normalize, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SHOTS = join(root, "screenshots", "latest");
const DIR = join(root, "review");
const CROPS = join(DIR, "crops");
const DB = join(DIR, "comments.json");
const FEEDBACK = join(DIR, "FEEDBACK.md");
const UI = join(root, "tools", "review", "index.html");
const PORT = Number(process.env.PORT || 4300);

mkdirSync(CROPS, { recursive: true });

// ---------- store ----------
const load = () => (existsSync(DB) ? JSON.parse(readFileSync(DB, "utf8")) : { next: 1, comments: [] });
const manifest = () => (existsSync(join(SHOTS, "manifest.json")) ? JSON.parse(readFileSync(join(SHOTS, "manifest.json"), "utf8")) : null);

function save(db) {
  writeFileSync(DB, JSON.stringify(db, null, 2));
  writeFileSync(FEEDBACK, feedbackMarkdown(db));
}

function where(c, m) {
  const g = m?.groups.find((x) => x.id === c.group);
  const s = g?.steps.find((x) => x.id === c.step);
  return `${g?.title ?? c.group} › ${s?.name ?? c.step} · ${c.variant}`;
}

function target(c) {
  const e = c.element;
  const parts = [];
  if (e) {
    const name = e.component ? `${e.component}` : `<${e.tag}>`;
    parts.push(`${name}${e.text ? ` "${e.text}"` : ""}${e.within && e.within !== e.component ? ` inside ${e.within}` : ""}`);
    parts.push(`\`${e.selector}\``);
  }
  if (c.kind === "area") parts.push(`area ${c.w}×${c.h} at ${c.x},${c.y}`);
  else parts.push(`point ${c.x},${c.y}`);
  return parts.join(" · ");
}

function feedbackMarkdown(db) {
  const m = manifest();
  const open = db.comments.filter((c) => c.status === "open");
  const done = db.comments.filter((c) => c.status === "resolved");
  const lines = [
    "# Fork review feedback",
    "",
    `${open.length} open, ${done.length} resolved. Generated by tools/review.mjs; edit comments in the review app, not here.`,
    "",
    "Coordinates are CSS pixels on the full-page screenshot. Crops are in review/crops/.",
    "",
  ];
  const section = (title, list) => {
    if (!list.length) return;
    lines.push(`## ${title}`, "");
    for (const c of list) {
      lines.push(`### ${c.id} · ${where(c, m)}`, "");
      lines.push(`- **Screen:** \`${c.url ?? "?"}\` as ${c.persona ?? "signed out"} (${c.group}/${c.step})`);
      lines.push(`- **Pointing at:** ${target(c)}`);
      lines.push(`- **Crop:** review/crops/${c.id}.png`);
      lines.push(`- **Screenshot:** screenshots/latest/${c.file ?? "?"}`);
      lines.push("", `> ${c.text.replace(/\n/g, "\n> ")}`, "");
      for (const r of c.replies ?? []) lines.push(`**${r.by}:** ${r.text}`, "");
    }
  };
  section("Open", open);
  section("Resolved", done);
  return lines.join("\n");
}

// ---------- CLI ----------
const [cmd, id, ...rest] = process.argv.slice(2);
if (cmd && cmd !== "serve") {
  const db = load();
  const c = id ? db.comments.find((x) => x.id === id) : null;
  if (cmd === "list") {
    const m = manifest();
    const open = db.comments.filter((x) => x.status === "open");
    if (!open.length) console.log("No open feedback.");
    for (const x of open) console.log(`${x.id}  ${where(x, m)}\n    ${target(x)}\n    "${x.text}"\n`);
    process.exit(0);
  }
  if (!c) {
    console.error(`No comment ${id}. Try: node tools/review.mjs list`);
    process.exit(1);
  }
  const text = rest.join(" ").trim();
  if (cmd === "reply" || cmd === "resolve") {
    if (text) (c.replies ??= []).push({ by: "Claude", text, at: new Date().toISOString() });
    if (cmd === "resolve") c.status = "resolved";
  } else if (cmd === "reopen") c.status = "open";
  else {
    console.error(`Unknown command ${cmd}.`);
    process.exit(1);
  }
  save(db);
  console.log(`${c.id}: ${c.status}`);
  process.exit(0);
}

// ---------- server ----------
const TYPES = { ".html": "text/html; charset=utf-8", ".json": "application/json", ".png": "image/png", ".js": "text/javascript" };

function sendFile(res, file) {
  if (!existsSync(file)) return send(res, 404, { error: "not found" });
  res.writeHead(200, { "content-type": TYPES[extname(file)] ?? "application/octet-stream", "cache-control": "no-store" });
  res.end(readFileSync(file));
}
function send(res, status, body) {
  res.writeHead(status, { "content-type": "application/json", "cache-control": "no-store" });
  res.end(JSON.stringify(body));
}
async function body(req) {
  let s = "";
  for await (const chunk of req) s += chunk;
  return s ? JSON.parse(s) : {};
}
/** Resolve a path inside a folder, refusing anything that climbs out of it. */
function inside(dir, rel) {
  const p = normalize(join(dir, decodeURIComponent(rel)));
  return p.startsWith(dir + sep) ? p : null;
}

createServer(async (req, res) => {
  try {
    const url = new URL(req.url ?? "/", `http://127.0.0.1:${PORT}`);
    const p = url.pathname;
    if (p === "/" || p === "/index.html") return sendFile(res, UI);
    if (p === "/api/manifest") return manifest() ? send(res, 200, manifest()) : send(res, 404, { error: "Run node tools/shoot.mjs first." });
    if (p.startsWith("/shots/")) {
      const f = inside(SHOTS, p.slice(7));
      return f ? sendFile(res, f) : send(res, 400, { error: "bad path" });
    }
    if (p.startsWith("/crops/")) {
      const f = inside(CROPS, p.slice(7));
      return f ? sendFile(res, f) : send(res, 400, { error: "bad path" });
    }
    if (p === "/api/comments" && req.method === "GET") return send(res, 200, load().comments);
    if (p === "/api/comments" && req.method === "POST") {
      const b = await body(req);
      const db = load();
      const m = manifest();
      const shot = m?.shots[`${b.group}/${b.step}/${b.variant}`];
      const c = {
        id: `c${db.next++}`,
        status: "open",
        group: b.group,
        step: b.step,
        variant: b.variant,
        kind: b.kind === "area" ? "area" : "point",
        x: Math.round(b.x),
        y: Math.round(b.y),
        w: Math.round(b.w ?? 0),
        h: Math.round(b.h ?? 0),
        element: b.element ?? null,
        text: String(b.text ?? "").slice(0, 4000),
        url: shot?.url ?? null,
        file: shot?.file ?? null,
        persona: m?.groups.find((g) => g.id === b.group)?.persona ?? null,
        shotAt: m?.generatedAt ?? null,
        createdAt: new Date().toISOString(),
        replies: [],
      };
      if (typeof b.crop === "string" && b.crop.startsWith("data:image/png;base64,")) {
        writeFileSync(join(CROPS, `${c.id}.png`), Buffer.from(b.crop.slice(22), "base64"));
      }
      db.comments.push(c);
      save(db);
      return send(res, 200, c);
    }
    const one = p.match(/^\/api\/comments\/(c\d+)$/);
    if (one) {
      const db = load();
      const c = db.comments.find((x) => x.id === one[1]);
      if (!c) return send(res, 404, { error: "no such comment" });
      if (req.method === "PATCH") {
        const b = await body(req);
        if (b.status === "open" || b.status === "resolved") c.status = b.status;
        if (typeof b.text === "string") c.text = b.text.slice(0, 4000);
        if (typeof b.reply === "string" && b.reply.trim()) (c.replies ??= []).push({ by: "Shaun", text: b.reply.trim(), at: new Date().toISOString() });
        save(db);
        return send(res, 200, c);
      }
      if (req.method === "DELETE") {
        db.comments = db.comments.filter((x) => x !== c);
        save(db);
        return send(res, 200, { ok: true });
      }
    }
    send(res, 404, { error: "not found" });
  } catch (e) {
    send(res, 500, { error: e instanceof Error ? e.message : String(e) });
  }
}).listen(PORT, "127.0.0.1", () => {
  console.log(`Fork review: http://127.0.0.1:${PORT}`);
  console.log(`Feedback is saved to ${FEEDBACK}`);
});
