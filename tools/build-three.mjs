// Builds client/fridge/vendor/three.js: only the parts of three.js Fork's 3D uses, tree-shaken and minified
// into one ES module. The platform's build doesn't minify, and full three.js was 1.7 MB of the app's
// JavaScript, parsed on every open. Run after changing which three.js classes client/fridge uses:
//   npx -y esbuild@0.24 --version >/dev/null && node tools/build-three.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
const entry = "/tmp/fork-three-entry.js";
writeFileSync(entry, `
export { AdditiveBlending, AddEquation, CustomBlending, OneFactor, ZeroFactor, BufferGeometry, CanvasTexture, CircleGeometry, CylinderGeometry, DirectionalLight, ExtrudeGeometry,
  Group, HemisphereLight, Material, MathUtils, Mesh, MeshBasicMaterial, MeshPhysicalMaterial, MeshStandardMaterial, NeutralToneMapping, NoColorSpace,
  Object3D, PCFShadowMap, PMREMGenerator, PerspectiveCamera, PlaneGeometry, RepeatWrapping, SRGBColorSpace, Scene,
  ShadowMaterial, Shape, ShapeGeometry, SphereGeometry, Texture, TextureLoader, Vector2, Vector3, WebGLRenderer } from "three";
export { Font } from "three/addons/loaders/FontLoader.js";
export { TextGeometry } from "three/addons/geometries/TextGeometry.js";
export { RoomEnvironment } from "three/addons/environments/RoomEnvironment.js";
export { RoundedBoxGeometry } from "three/addons/geometries/RoundedBoxGeometry.js";
export { toCreasedNormals } from "three/addons/utils/BufferGeometryUtils.js";
`);
const root = new URL("..", import.meta.url).pathname;
mkdirSync(root + "client/fridge/vendor", { recursive: true });
const out = root + "client/fridge/vendor/three.js";
execFileSync("npx", ["-y", "esbuild@0.24", entry, "--bundle", "--format=esm", "--minify", "--legal-comments=none", `--outfile=${out}`, "--log-level=warning"], { cwd: root, stdio: "inherit", env: { ...process.env, NODE_PATH: root + "node_modules" } });
const v = JSON.parse(readFileSync(root + "node_modules/three/package.json", "utf8")).version;
// Zero's compiler rejects the global `self`; in a page it is the same object as `window`.
const code = readFileSync(out, "utf8").replace(/typeof self<"u"&&(\w+)\.setContext\(self\)/g, 'typeof window<"u"&&$1.setContext(window)');
if (/\bself\b/.test(code)) throw new Error("vendor/three.js still mentions self; extend the rewrite in tools/build-three.mjs");
writeFileSync(out, `// three.js ${v} (MIT), only what client/fridge uses, minified. Generated by tools/build-three.mjs; don't edit.\n` + code);
console.log("wrote", out, Math.round(readFileSync(out).length / 1024), "KB");
