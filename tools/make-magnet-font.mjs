// Builds client/fridge/magnet-font.ts: Archivo Black, only the characters the magnets spell, in three.js's
// typeface format. Bundling it means the app never waits on a CDN or parses a TTF in the browser.
// Run: node tools/make-magnet-font.mjs <ArchivoBlack-Regular.ttf> <path to opentype.js package>
// (Archivo Black: https://fonts.google.com/specimen/Archivo+Black, SIL Open Font License.)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const [ttf, otDir] = process.argv.slice(2);
const opentype = createRequire(otDir + "/package.json")("opentype.js");
const buf = readFileSync(ttf);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'’?!,.&- ";
const round = Math.round, scale = 100000 / ((font.unitsPerEm || 2048) * 72);
const glyphs = {};
for (const ch of CHARS) {
  const g = font.charToGlyph(ch);
  let o = "";
  for (const c of g.path.commands) {
    const t = c.type.toLowerCase() === "c" ? "b" : c.type.toLowerCase();
    o += t + " ";
    if (c.x !== undefined) o += round(c.x * scale) + " " + round(c.y * scale) + " ";
    if (c.x1 !== undefined) o += round(c.x1 * scale) + " " + round(c.y1 * scale) + " ";
    if (c.x2 !== undefined) o += round(c.x2 * scale) + " " + round(c.y2 * scale) + " ";
  }
  glyphs[ch] = { ha: round(g.advanceWidth * scale), x_min: round((g.xMin ?? 0) * scale), x_max: round((g.xMax ?? 0) * scale), o: o.trim() };
}
const data = {
  glyphs, familyName: "Archivo Black", ascender: round(font.ascender * scale), descender: round(font.descender * scale),
  underlinePosition: font.tables.post.underlinePosition, underlineThickness: font.tables.post.underlineThickness,
  boundingBox: { xMin: font.tables.head.xMin, xMax: font.tables.head.xMax, yMin: font.tables.head.yMin, yMax: font.tables.head.yMax }, resolution: 1000,
};
writeFileSync(new URL("../client/fridge/magnet-font.ts", import.meta.url),
  `// Archivo Black (SIL Open Font License), only the characters the magnets spell, in three.js's typeface format.\n// Generated by tools/make-magnet-font.mjs; don't edit by hand.\nexport const MAGNET_FONT = ${JSON.stringify(data)};\n`);
console.log("glyphs:", Object.keys(glyphs).length);
